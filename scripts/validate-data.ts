/**
 * Dataset linter: `npm run validate-data`. Also run by the test suite.
 * `npm run validate-data -- --review` also writes docs/DATA_REVIEW.md.
 */
import { writeFileSync } from 'node:fs';
import { allPacks, baseBundle } from '../src/data/bundle';
import { Animal, FORM_KINDS, Dataset, formKind, mergePacks, validatePacks } from '../src/data/dataset';
import { buildVocab } from '../src/nn/vocab';

const bundle = baseBundle();
const vocab = buildVocab(bundle.vocabSpec, bundle.languages, bundle.forms);
const codes = bundle.languages.map((l) => l.code);
const wordForms = bundle.forms.filter((f) => f !== 'name');
const errors = validatePacks(allPacks(), vocab, codes, bundle.forms);

for (const pack of allPacks()) {
  const animals = mergePacks([pack]);
  const unseen = animals.filter((x) => x.split === 'unseen').length;
  const parts = codes.map((lang) => {
    const counts = Object.fromEntries(FORM_KINDS.map((k) => [k, 0]));
    let n = 0;
    for (const a of animals) for (const f of wordForms) {
      const w = a.forms[lang]?.[f];
      if (w) { counts[formKind(a.names[lang], w)]++; n++; }
    }
    return `${lang}: ${n} forms (${FORM_KINDS.map((k) => `${k} ${counts[k]}`).join(', ')})`;
  });
  const unsure = animals.reduce((n, a) => n + a.unsure.length, 0);
  console.log(`${pack.pack.padEnd(12)} ${String(animals.length).padStart(4)} animals | ${unseen} unseen | ${unsure} unsure | ${parts.join(' | ')}`);
}
console.log(`vocabulary: ${vocab.size} tokens`);

if (process.argv.includes('--review')) {
  const ds = new Dataset(bundle);
  writeFileSync('docs/DATA_REVIEW.md', reviewDoc(ds.animals));
  console.log('wrote docs/DATA_REVIEW.md');
}

if (errors.length) {
  console.error(`\n${errors.length} problem(s):`);
  for (const e of errors) console.error(' - ' + e);
  process.exit(1);
}
console.log('Data OK');

function reviewDoc(animals: Animal[]): string {
  const cell = (a: Animal, lang: string, form: string) => {
    const w = a.forms[lang]?.[form];
    if (!w) return '—';
    const alts = a.formsAlt[lang]?.[form];
    const flag = a.unsure.includes(`${lang}.${form}`) ? ' ⚠️' : '';
    const kind = formKind(a.names[lang], w);
    const mark = kind === 'pattern' ? '' : kind === 'partly' ? ' ◐' : ' ●';
    return `**${w}**${mark}${alts ? ` (${alts.join(', ')})` : ''}${flag}`;
  };
  const withForms = animals.filter((a) => Object.keys(a.forms).length > 0);
  const lines = [
    '# Data review: animal word forms',
    '',
    'Generated by `npm run validate-data -- --review` from `data/animals.base.json`. Edit the JSON, not this file.',
    '',
    '**Please check:** spelling and diacritics, whether each word is the natural one, and every ⚠️ (unsure) entry.',
    'Delete a form you do not like rather than keeping a doubtful one: a missing form becomes something the model invents.',
    '',
    'Marks: ◐ = partly follows the name (lev → lvice), ● = irregular (pes → štěně), no mark = keeps the name (tygr → tygřice).',
    '`unseen` animals are never trained on; they test whether the model learned the patterns.',
    '',
  ];
  for (const lang of codes) {
    lines.push(`## ${bundle.languages.find((l) => l.code === lang)!.name.en}`, '', `| name | ${wordForms.join(' | ')} | split |`, `|---|${wordForms.map(() => '---|').join('')}---|`);
    for (const a of withForms.filter((x) => x.forms[lang])) {
      lines.push(`| ${a.names[lang]} | ${wordForms.map((f) => cell(a, lang, f)).join(' | ')} | ${a.split === 'unseen' ? '**unseen**' : ''} |`);
    }
    lines.push('');
  }
  const none = animals.filter((a) => codes.some((l) => !a.forms[l]));
  lines.push(
    '## Animals without forms (the model will invent them)', '',
    codes.map((l) => `- **${l}:** ${none.filter((a) => !a.forms[l]).map((a) => a.names[l]).join(', ')}`).join('\n'), '',
  );
  return lines.join('\n');
}
